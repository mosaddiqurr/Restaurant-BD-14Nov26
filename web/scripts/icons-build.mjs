/* Builds public/icons/{regular,fill,bold}.svg sprites from the official Phosphor icons listed in scripts/icons-used.json.
   Add a name to that list (or run icons-scan.mjs) and run this again. */
import fs from 'node:fs';
const names = JSON.parse(fs.readFileSync('scripts/icons-used.json', 'utf8'));
fs.mkdirSync('public/icons', { recursive: true });
for (const w of ['regular', 'fill', 'bold']) {
  const out = names.map(n => {
    const f = `node_modules/@phosphor-icons/core/assets/${w}/${n}${w === 'regular' ? '' : '-' + w}.svg`;
    if (!fs.existsSync(f)) return '';
    const s = fs.readFileSync(f, 'utf8'); const inner = s.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    return `<symbol id="${n}" viewBox="0 0 256 256">${inner}</symbol>`;
  }).join('');
  fs.writeFileSync(`public/icons/${w}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor">${out}</svg>`);
}
fs.writeFileSync('components/ui/icon-names.ts', '/* generated by scripts/icons-build.mjs */\nexport type IconName =\n' + names.map(n => `  | '${n}'`).join('\n') + ';\n');
console.log('icons:', names.length);
